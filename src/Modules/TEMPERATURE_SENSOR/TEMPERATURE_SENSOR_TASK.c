#include "TEMPERATURE_SENSOR_TASK.h"

void TEMPERATURE_SENSOR_TASK(void) {
    uint16_t ADC_BYTE_TEMPERATURE = ADC_READ(TEMPERATURE_SENSOR_PIN); 

    uint8_t ADC_MOST_MEANINGFUL_BYTE = (ADC_BYTE_TEMPERATURE >> 8) & 0xFF;
    uint8_t ADC_LEAST_MEANINGFUL_BYTE = ADC_BYTE_TEMPERATURE & 0xFF;
    
    USART_SEND(TEMPERATURE_MESSAGE);
    USART_SEND(ADC_MOST_MEANINGFUL_BYTE); 
    USART_SEND(ADC_LEAST_MEANINGFUL_BYTE);  

}